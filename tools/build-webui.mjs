/**
 * 把 life.js / qq.js / bili.js 内联进 client.js。
 *
 * Coopanion 只发 manifest 声明的 webUiClient 这一个 JS 文件，浏览器端不能
 * import 子文件（会 404）。每个面板模块包进独立 IIFE，避免顶层变量互相覆盖；
 * client.base.js 只负责把三个 panels 合并导出。
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', 'src', 'webui');
const modules = [
  ['LIFE_PANELS', 'life.js'],
  ['QQ_PANELS', 'qq.js'],
  ['BILI_PANELS', 'bili.js'],
];
const chunks = [];
for (const [name, file] of modules) {
  const code = readFileSync(join(dir, file), 'utf8').replace(/export default\s+/, 'return ');
  chunks.push(`const ${name} = (() => {\n${code}\n})();`);
}
let base = readFileSync(join(dir, 'client.base.js'), 'utf8');
base = base.replace(/^import .* from '\.\/(?:life|qq|bili)\.js';\r?\n/gm, '');
base = base
  .replace('...life.panels,', '...LIFE_PANELS.panels,')
  .replace('...qq.panels,', '...QQ_PANELS.panels,')
  .replace('...bili.panels,', '...BILI_PANELS.panels,');
const banner = '/* generated by tools/build-webui.mjs — edit life.js / qq.js / bili.js / client.base.js, then rebuild */\n';
writeFileSync(join(dir, 'client.js'), `${banner}${chunks.join('\n\n')}\n${base}`, 'utf8');
console.log(`client.js: ${chunks.reduce((sum, chunk) => sum + chunk.length, 0) + base.length} chars`);
